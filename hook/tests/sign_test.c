static int failed;

static void check(const char *what, int got, int want) {
    printf("  %-58s %s\n", what, got == want ? "ok" : "FAILED");
    failed += got != want;
}

/* S replaced by S + L: the same point, a non-canonical scalar */
static void add_order(unsigned char *s) {
    int carry = 0;
    for (int i = 0; i < 32; ++i) {
        int v = s[i] + (int)ED_L[i] + carry;
        s[i] = (unsigned char)v;
        carry = v >> 8;
    }
}

static void test_vector(const Vector *v) {
    static unsigned char message[2048];
    unsigned char key[32], signature[64];
    char what[96];
    memcpy(key, v->key, 32);
    memcpy(signature, v->signature, 64);
    memcpy(message, v->message, v->size);
    message[v->size] = 0;
    printf("== %s (%u bytes)\n", v->name, (unsigned)v->size);
    check("verifies", azimuth_sign_verify(signature, message, v->size, key), 1);
    if (v->size) {
        message[v->size / 2] ^= 0x04;
        check("flipped bit in the message is refused", azimuth_sign_verify(signature, message, v->size, key), 0);
        message[v->size / 2] ^= 0x04;
    }
    check("one byte more of message is refused", azimuth_sign_verify(signature, message, v->size + 1, key), 0);
    for (int byte = 0; byte < 63; byte += 21) {
        signature[byte] ^= 0x10;
        snprintf(what, sizeof(what), "flipped bit in signature byte %d is refused", byte);
        check(what, azimuth_sign_verify(signature, message, v->size, key), 0);
        signature[byte] ^= 0x10;
    }
    signature[63] ^= 0x01;
    check("flipped bit in signature byte 63 is refused", azimuth_sign_verify(signature, message, v->size, key), 0);
    signature[63] ^= 0x01;
    for (int byte = 0; byte < 32; byte += 31) {
        key[byte] ^= 0x01;
        snprintf(what, sizeof(what), "flipped bit in key byte %d is refused", byte);
        check(what, azimuth_sign_verify(signature, message, v->size, key), 0);
        key[byte] ^= 0x01;
    }
    add_order(signature + 32);
    check("S + L (non-canonical) is refused", azimuth_sign_verify(signature, message, v->size, key), 0);
}

static int parse_hex(const char *text, unsigned char *out, size_t size) {
    if (strlen(text) != 2 * size) {
        return 0;
    }
    for (size_t i = 0; i < size; ++i) {
        unsigned v;
        if (sscanf(text + 2 * i, "%2x", &v) != 1) {
            return 0;
        }
        out[i] = (unsigned char)v;
    }
    return 1;
}

int main(int argc, char **argv) {
    for (size_t i = 0; i < sizeof(vectors) / sizeof(vectors[0]); ++i) {
        test_vector(&vectors[i]);
    }
    if (argc == 3) {
        unsigned char digest[32], signature[64], other[32];
        FILE *f = fopen(argv[2], "rb");
        size_t got = f ? fread(signature, 1, 64, f) : 0;
        if (f) {
            got += fread(other, 1, 1, f);
            fclose(f);
        }
        printf("== release key: the release signature of \"%s%s\"\n", AZIMUTH_SIGN_PREFIX, argv[1]);
        if (!parse_hex(argv[1], digest, 32) || got != 64) {
            printf("  bad arguments (digest hex, 64-byte signature file)\n");
            return 1;
        }
        check("the update line verifies with the embedded key",
              azimuth_sign_update_ok(signature, digest, azimuth_sign_release_key), 1);
        digest[7] ^= 0x80;
        check("another DLL (flipped digest bit) is refused",
              azimuth_sign_update_ok(signature, digest, azimuth_sign_release_key), 0);
        digest[7] ^= 0x80;
        signature[40] ^= 0x02;
        check("flipped signature bit is refused", azimuth_sign_update_ok(signature, digest, azimuth_sign_release_key), 0);
        signature[40] ^= 0x02;
        memcpy(other, vectors[0].key, 32);
        check("another key (RFC TEST 1's) is refused", azimuth_sign_update_ok(signature, digest, other), 0);
        add_order(signature + 32);
        check("S + L (non-canonical) is refused", azimuth_sign_update_ok(signature, digest, azimuth_sign_release_key), 0);
    } else {
        printf("== release key: no signature given, skipped\n");
    }
    printf("%s\n", failed ? "FAILED" : "all ok");
    return failed ? 1 : 0;
}
